// ไหนมี keyword ชนคำใน connector หรือฟังแปลกตามเกณฑ์ข้างบน
// positionId เลือกชุดประโยคเชื่อมของตำแหน่งนั้น (ไม่พบ → ใช้ตำแหน่งแรกของหัวข้อแทน กันแอปพัง)
// used ให้ส่งตัวเดียวกันทุกใบในชุด เพื่อไม่ให้ประโยคเปิด/ประโยคเชื่อมซ้ำกันภายในชุด
export function composeInterpretation(
  card: TarotCard,
  reversed: boolean,
  topicId: TopicId,
  positionLabel: string,
  positionId?: string,
  used: UsedTemplates = createUsedTemplates()
): Interpretation {
  const pool = reversed ? card.reversed : card.upright;
  const topicSlots = CONNECTORS[topicId];
  const slotKey = positionId && topicSlots[positionId] ? positionId : Object.keys(topicSlots)[0];
  const side = reversed ? 'reversed' : 'upright';
  const connectors = topicSlots[slotKey][side];
  const connectorKey = (index: number) => `${topicId}.${slotKey}.${side}.${index}`;

  // เลือกได้เฉพาะแบบที่ยังไม่ถูกใช้ในชุดนี้ — ถ้าใช้ครบทุกแบบแล้ว (ไม่ควรเกิดกับชุด 3 ใบ)
  // ก็ยอมให้ซ้ำได้ ดีกว่าไม่มีประโยคให้เลือก
  const freeOpeners = OPENERS.map((_, i) => i).filter((i) => !used.openers.has(i));
  const openerChoices = freeOpeners.length > 0 ? freeOpeners : OPENERS.map((_, i) => i);
  const freeConnectors = connectors.map((_, i) => i).filter((i) => !used.connectors.has(connectorKey(i)));
  const connectorChoices = freeConnectors.length > 0 ? freeConnectors : connectors.map((_, i) => i);

  // สำคัญ: ต้องกำหนด body ทุกรอบ (ไม่ใช้ continue ข้ามทิ้งเฉย ๆ) ไม่งั้นถ้าทุกรอบชนกัน
  // หมดจะเหลือ body เป็นค่าว่าง — รอบสุดท้ายเสมอมีค่าเก็บไว้เป็น fallback ที่ปลอดภัยกว่า
  let body = '';
  let openerIndex = openerChoices[0];
  let connectorIndex = connectorChoices[0];
  for (let attempt = 0; attempt < 5; attempt++) {
    openerIndex = pickRandom(openerChoices);
    connectorIndex = pickRandom(connectorChoices);
    const opener = OPENERS[openerIndex](card.thaiName, positionLabel);
    const keywordParts = pickKeywordParts(pool);
    const connectorFn = connectors[connectorIndex];
    const collides = keywordCollidesWithConnector(connectorFn(''), keywordParts);

    const connector = connectorFn(joinKeywordParts(keywordParts));
    body = `${opener} ${connector}`;
    if (!collides && !isAwkward(body)) break;
  }

  used.openers.add(openerIndex);
  used.connectors.add(connectorKey(connectorIndex));
  return { body, quote: card.quote };
}
